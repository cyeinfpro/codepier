#!/usr/bin/env node
import { readFileSync, readdirSync } from 'node:fs';
import { extname } from 'node:path';

const rules = [
  [/(不会|不能|不是|并非|不代表|不等于|不证明)[^。；]{0,30}[，；](也|且|并)?(不会|不能|不是|不)/u, '连续否定', 'error'],
  [/(证据|回执|原操作|验收|工具合约)/u, '操作记录和诊断用词', 'review'],
  [/\p{Script=Han}（(?!(?:KiB|MiB|GiB|TiB|ms|Hz|MHz|GHz)）)[A-Za-z][A-Za-z ]*）/u, '英文括注', 'error'],
  [/请[^。]{0,30}，不要/u, '请……不要……', 'error'],
  [/[A-Z]{3,}( \/ [A-Z]{3,})+/u, '装饰英文', 'error'],
  [/(节点|家里电脑|映射)/u, '设备和目录术语', 'review'],
];
const root = new URL('../', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('./ui-copy-sources.json', import.meta.url), 'utf8'));
const sources = [];
function collect(directory) {
  for (const entry of readdirSync(new URL(directory + '/', root), { withFileTypes: true })) {
    const path = directory + '/' + entry.name;
    if (entry.isDirectory() && !manifest.excludeDirectories.includes(entry.name)) collect(path);
    else if (entry.isFile() && manifest.extensions.includes(extname(path)) && !manifest.excludeFiles.includes(path)) sources.push(path);
  }
}
for (const directory of manifest.roots) collect(directory);
sources.sort();
const skippedGenerated = [];
const findings = [];
for (const file of sources) {
  const source = readFileSync(new URL(file, root), 'utf8');
  if (/^(?:\/\/|<!--) Generated by /u.test(source)) { skippedGenerated.push(file); continue; }
  for (const [index, line] of source.split('\n').entries()) {
    if (/^\s*(\/\/|\/\*|\*)/.test(line)) continue;
    for (const [pattern, label, severity] of rules) {
      const match = line.match(pattern);
      if (!match) continue;
      // Protocol names and units convey a real user choice, unlike decorative headings.
      if (label === '装饰英文' && ['HTTP / HTTPS', 'GPT / MCP'].includes(match[0])) continue;
      findings.push({ file, line: index + 1, label, severity: manifest.reviewOnlyExtensions.includes(extname(file)) ? 'review' : severity, match: match[0].slice(0, 40) });
    }
  }
}
const errors = findings.filter((item) => item.severity === 'error');
const audit = process.argv.includes('--audit');
if (process.argv.includes('--coverage')) console.log(JSON.stringify({ sources: sources.filter(f => !skippedGenerated.includes(f)), skippedGenerated, manifestVersion: manifest.version }, null, 2));
for (const item of audit ? findings : errors) {
  console.log(item.file + ':' + item.line + '  [' + item.label + ']  ' + item.match);
}
console.log('\n明确文案问题 ' + errors.length + ' 处；场景用词提示 ' +
  (findings.length - errors.length) + ' 处（--audit 查看，诊断和权限说明可保留）。');
const max = Number(process.argv.find((arg) => arg.startsWith('--max='))?.slice(6) ?? Infinity);
process.exitCode = Number.isNaN(max) || findings.length > max ||
  (process.argv.includes('--check') && errors.length > 0) ? 1 : 0;
