#!/usr/bin/env python3
"""Generate standalone bootstrap copies from their reviewed shared implementations.

Install and lifecycle helpers run without the installed package (the lifecycle
helper is copied to an OS temporary directory before replacing runtime).
"""

from __future__ import annotations
import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FUNCTIONS = (
    "is_legacy_launchd_name",
    "_read_owned_service_file",
    "_launchd_service_name",
    "systemd_quote",
)


def functions(source):
    return {node.name: node for node in ast.parse(source).body if isinstance(node, ast.FunctionDef)}


def outputs(root=ROOT):
    canonical = (root / "shared/brand_migration.py").read_text()
    definitions = functions(canonical)
    canonical_lines = canonical.splitlines(keepends=True)
    result = {}
    for name in ("scripts/install_agent.py", "scripts/agent_lifecycle.py"):
        source = (root / name).read_text()
        lines = source.splitlines(keepends=True)
        selected = [node for key, node in functions(source).items() if key in FUNCTIONS]
        for node in sorted(selected, key=lambda entry: entry.lineno, reverse=True):
            original = definitions[node.name]
            lines[node.lineno - 1 : node.end_lineno] = canonical_lines[
                original.lineno - 1 : original.end_lineno
            ]
        result[name] = "".join(lines)
    result["scripts/panel_update_source.py"] = (
        "# Generated by scripts/sync_standalone_helpers.py; edit shared/release_source.py.\n"
        + (root / "shared/release_source.py").read_text()
    )
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    changed = []
    for name, source in outputs().items():
        path = ROOT / name
        if path.read_text() != source:
            changed.append(name)
            if not args.check:
                path.write_text(source)
    print("Standalone helper drift: " + (", ".join(changed) or "none"))
    return int(args.check and bool(changed))


if __name__ == "__main__":
    raise SystemExit(main())
