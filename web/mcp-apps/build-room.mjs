import * as esbuild from 'esbuild';
import * as prettier from 'prettier';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = resolve(here, '..');
const check = process.argv.includes('--check');
const generated = new Map();
const options = await prettier.resolveConfig(resolve(web, 'collaboration-room.js'));
const bundle = await esbuild.build({
  absWorkingDir: web,
  entryPoints: ['collaboration-room/index.mjs'],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  write: false,
  banner: { js: '// Generated by web/mcp-apps/build-room.mjs; edit web/collaboration-room/*.mjs.' },
});
generated.set(
  'collaboration-room.js',
  await prettier.format(bundle.outputFiles[0].text, {
    ...options,
    parser: 'babel',
  }),
);

async function orderedSource(directory, extension) {
  const files = JSON.parse(await readFile(resolve(web, directory, 'manifest.json'), 'utf8'));
  if (
    !Array.isArray(files) ||
    !files.length ||
    new Set(files).size !== files.length ||
    files.some(
      (name) =>
        typeof name !== 'string' || !/^[a-z-]+\.(css|js)$/.test(name) || !name.endsWith(extension),
    )
  )
    throw new Error('Invalid source manifest: ' + directory);
  const parts = await Promise.all(
    files.map((name) => readFile(resolve(web, directory, name), 'utf8')),
  );
  return parts.join('\n');
}
generated.set(
  'chat.js',
  await prettier.format(
    '// Generated by web/mcp-apps/build-room.mjs; edit web/chat/*.js.\n' +
      (await orderedSource('chat', '.js')),
    { ...options, parser: 'babel' },
  ),
);
for (const name of ['chat', 'collaboration-room']) {
  generated.set(
    name + '.css',
    await prettier.format(
      '/* Generated by web/mcp-apps/build-room.mjs; edit web/' +
        name +
        '/styles/*.css. */\n' +
        (await orderedSource(name + '/styles', '.css')),
      { ...options, parser: 'css' },
    ),
  );
}
const changed = [];
for (const [name, content] of generated) {
  const path = resolve(web, name);
  if ((await readFile(path, 'utf8')) === content) continue;
  changed.push(name);
  if (!check) await writeFile(path, content);
}
console.log(
  (check ? 'Outdated conversation assets: ' : 'Generated conversation assets: ') +
    (changed.join(', ') || 'none'),
);
if (check && changed.length) process.exitCode = 1;
