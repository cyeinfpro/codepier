import { build, transform } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { codeOptions } from './build-options.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const web = resolve(here, '..');
const check = process.argv.includes('--check');
const packages = [
  '@xterm/xterm',
  '@xterm/addon-fit',
  '@xterm/addon-search',
  '@xterm/addon-web-links',
  '@xterm/addon-webgl',
];
const packageInfo = [],
  notices = [];
for (const name of packages) {
  const directory = resolve(here, 'node_modules', name);
  const meta = JSON.parse(await readFile(resolve(directory, 'package.json'), 'utf8'));
  packageInfo.push({ name: meta.name, version: meta.version, license: meta.license });
  const names = (await readdir(directory))
    .filter((name) => /^(LICENSE|LICENCE|NOTICE|COPYING)/i.test(name))
    .sort();
  if (!names.length) throw new Error(`Missing license text for ${name}`);
  const texts = await Promise.all(
    names.map(
      async (file) =>
        `-- ${file} --\n${(await readFile(resolve(directory, file), 'utf8')).replace(/\r\n?/g, '\n').trimEnd()}`,
    ),
  );
  notices.push(
    `${'='.repeat(72)}\n${meta.name}@${meta.version}\nLicense: ${meta.license}\n\n${texts.join('\n\n')}`,
  );
}

const result = await build({
  absWorkingDir: web,
  entryPoints: ['vps-terminal/index.mjs'],
  nodePaths: [resolve(here, 'node_modules')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  write: false,
  ...codeOptions,
  banner: { js: '// Generated by web/mcp-apps/build-terminal.mjs; edit web/vps-terminal/*.mjs.' },
});
const baseCss = await readFile(resolve(here, 'node_modules/@xterm/xterm/css/xterm.css'), 'utf8');
const ownCss = await readFile(resolve(web, 'vps-terminal/styles.css'), 'utf8');
const css = await transform(`${baseCss}\n${ownCss}`, {
  loader: 'css',
  minify: true,
  legalComments: 'eof',
  target: 'es2022',
});
const outputs = new Map([
  ['vps-terminal.js', result.outputFiles[0].text],
  ['vps-terminal.css', '/* Generated by web/mcp-apps/build-terminal.mjs. */\n' + css.code],
  ['vps-terminal/THIRD_PARTY_NOTICES.txt', notices.join('\n\n').trimEnd() + '\n'],
]);
const manifest = Object.fromEntries(
  [...outputs].map(([path, text]) => [
    path,
    { bytes: Buffer.byteLength(text), sha256: createHash('sha256').update(text).digest('hex') },
  ]),
);
outputs.set(
  'vps-terminal/manifest.json',
  JSON.stringify({ protocol_version: 1, packages: packageInfo, outputs: manifest }, null, 2) + '\n',
);
const changed = [];
for (const [path, text] of outputs) {
  let previous = null;
  try {
    previous = await readFile(resolve(web, path), 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (previous === text) continue;
  changed.push(path);
  if (!check) await writeFile(resolve(web, path), text);
}
console.log(`${check ? 'Outdated' : 'Generated'} terminal assets: ${changed.join(', ') || 'none'}`);
if (check && changed.length) process.exitCode = 1;
